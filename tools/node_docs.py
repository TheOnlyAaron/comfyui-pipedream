"""
Fill the generated reference block of each node page in ``web/docs``.

Every ``web/docs/<Class>.md`` holds hand-written text plus one block between
the lines ``<!-- reference:start -->`` and ``<!-- reference:end -->`` with the
node's inputs, outputs and output-node status, read from the node classes.
Run from anywhere::

    python tools/node_docs.py            # update the pages (creates missing ones)
    python tools/node_docs.py --check    # exit 1 when a page is missing or stale

Standard library only.  The pack folder name contains a hyphen, so it is
loaded with importlib under the package name ``pipedream_docs``.  Importing
the nodes needs ``torch`` (``nodes/ocio.py`` uses it in an annotation); when
it is not installed an empty stand-in module is used for the import.  The
settings are reset to the built-in defaults first, so a user or facility
``pipedream.toml`` never leaks into the docs.
"""

import argparse
import importlib
import importlib.util
import os
import re
import sys
import types

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKAGE = "pipedream_docs"
DOCS_DIR = os.path.join(ROOT, "web", "docs")

START = "<!-- reference:start -->"
END = "<!-- reference:end -->"
NOTICE = "<!-- Generated by tools/node_docs.py. Edit the node definition, not this block. -->"
EMOJI_PREFIX = "\U0001F4AD "
MAX_CHOICES = 6
MIN_FAMILY = 3  # numbered inputs are collapsed from this many members up


# ---------------------------------------------------------------- loading

def load_nodes() -> list:
    """Import the pack and return the documented node classes (no deprecated aliases)."""
    stubbed = False
    if importlib.util.find_spec("torch") is None:
        stub = types.ModuleType("torch")
        stub.Tensor = object
        sys.modules["torch"] = stub
        stubbed = True
    try:
        if PACKAGE not in sys.modules:
            spec = importlib.util.spec_from_file_location(
                PACKAGE, os.path.join(ROOT, "__init__.py"),
                submodule_search_locations=[ROOT])
            module = importlib.util.module_from_spec(spec)
            sys.modules[PACKAGE] = module
        nodes = importlib.import_module(f"{PACKAGE}.nodes")
        settings = importlib.import_module(f"{PACKAGE}.core.settings")
        settings.load(user_path=None, facility_path="")
    finally:
        if stubbed:
            sys.modules.pop("torch", None)
    return [c for c in nodes.ALL_NODES if not getattr(c, "DEPRECATED", False)]


def display_name(cls) -> str:
    name = getattr(cls, "DISPLAY_NAME", cls.__name__)
    return name[len(EMOJI_PREFIX):] if name.startswith(EMOJI_PREFIX) else name


# ------------------------------------------------------------ formatting

def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\r", "").replace("\n", " ").strip()


def _type_name(t) -> str:
    return "any" if t == "*" else str(t)


def _choices(values) -> str:
    values = [str(v) for v in values]
    if len(values) > MAX_CHOICES:
        return ", ".join(values[:3]) + f", \u2026 ({len(values)} choices)"
    return ", ".join(values)


def _default(spec, opts) -> str:
    kind = spec[0]
    if "default" in opts:
        value = opts["default"]
    elif isinstance(kind, list) and kind:
        value = kind[0]  # ComfyUI starts a combo on its first choice
    elif kind == "COMBO" and opts.get("options"):
        value = opts["options"][0]
    else:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if value == "":
        return '`""`'
    return f"`{_cell(value)}`"


def _describe(spec) -> tuple[str, str, str]:
    """Return (type, default, tooltip) for one INPUT_TYPES entry."""
    kind = spec[0]
    opts = spec[1] if len(spec) > 1 and isinstance(spec[1], dict) else {}
    if isinstance(kind, (list, tuple)):
        type_ = _choices(kind)
    elif kind == "COMBO" and opts.get("options"):
        type_ = _choices(opts["options"])
    else:
        type_ = _type_name(kind)
    if opts.get("forceInput"):
        type_ += " (socket)"
    return type_, _default(spec, opts), opts.get("tooltip", "")


def _family(name: str):
    """Split a numbered input name into (family key, index); None when not numbered."""
    m = re.fullmatch(r"custom_(\d+)_(name|value)", name)
    if m:
        return f"custom_N_{m.group(2)}", int(m.group(1))
    m = re.fullmatch(r"(.+)_(\d+)", name)
    if m:
        return m.group(1) + "_N", int(m.group(2))
    return None


def _collapse(names: list[str]) -> list[tuple[str, list[str]]]:
    """Group *names* into rows: [(label, [members])]; numbered families become one row."""
    families: dict[str, list[tuple[int, str]]] = {}
    for name in names:
        fam = _family(name)
        if fam:
            families.setdefault(fam[0], []).append((fam[1], name))
    # A base name with numbered siblings (exr_metadata, exr_metadata_2, ...) joins them.
    for key, members in families.items():
        base = key[:-2]
        if key.endswith("_N") and base in names and not _family(base):
            members.append((1, base))
    collapsed = {k: sorted(v) for k, v in families.items() if len(v) >= MIN_FAMILY}
    rows, done = [], set()
    for name in names:
        if name in done:
            continue
        fam = _family(name)
        key = fam[0] if fam else name + "_N"
        if key in collapsed and (fam or any(m == name for _, m in collapsed[key])):
            members = [m for _, m in collapsed[key]]
            done.update(members)
            rows.append((_family_label(members), members))
        else:
            done.add(name)
            rows.append((name, [name]))
    return rows


def _family_label(members: list[str]) -> str:
    first, last = members[0], members[-1]
    if re.fullmatch(r".+_\d+", first):
        return f"{first} \u2026 {last}"
    if _family(first) is None:  # unnumbered base: exr_metadata, exr_metadata_2 ... _8
        suffix = "_" + last.rsplit("_", 1)[1]
        return f"{first}, {members[1]} \u2026 {suffix}"
    return f"{first} \u2026 {last}"


def render_inputs(cls) -> str:
    types_ = cls.INPUT_TYPES()
    lines = ["| Name | Type | Default | Required | Description |",
             "|------|------|---------|----------|-------------|"]
    count = 0
    for section, required in (("required", "required"), ("optional", "optional")):
        entries = types_.get(section) or {}
        for label, members in _collapse(list(entries)):
            type_, default, tip = _describe(entries[members[0]])
            lines.append(f"| `{_cell(label)}` | {_cell(type_)} | {default} | {required} | {_cell(tip)} |")
            count += 1
    if not count:
        return "This node has no inputs."
    return "\n".join(lines)


def render_outputs(cls) -> str:
    kinds = tuple(getattr(cls, "RETURN_TYPES", ()) or ())
    if not kinds:
        return "This node has no outputs."
    names = tuple(getattr(cls, "RETURN_NAMES", ()) or kinds)
    tips = tuple(getattr(cls, "OUTPUT_TOOLTIPS", ()) or ())
    lines = ["| Name | Type | Description |", "|------|------|-------------|"]
    for i, kind in enumerate(kinds):
        name = names[i] if i < len(names) else kind
        tip = tips[i] if i < len(tips) else ""
        lines.append(f"| `{_cell(name)}` | {_cell(_type_name(kind))} | {_cell(tip)} |")
    return "\n".join(lines)


def render_block(cls) -> str:
    """The text that belongs between the markers (no trailing newline)."""
    if getattr(cls, "OUTPUT_NODE", False):
        note = "This is an output node: it runs whenever it is in the graph, even with nothing connected after it."
    else:
        note = "This is not an output node: it runs only when another node needs its result."
    return "\n".join([
        NOTICE, "", "### Inputs", "", render_inputs(cls), "",
        "### Outputs", "", render_outputs(cls), "", note,
    ])


# ----------------------------------------------------------------- pages

def skeleton(cls) -> str:
    return "\n".join([
        f"# {display_name(cls)}", "", "TODO: describe this node.", "",
        "## Inputs and outputs", "", START, render_block(cls), END, ""])


def _split(text: str):
    """Return (before, old block, after) around the marker lines, or None."""
    lines = text.splitlines(keepends=True)
    start = [i for i, l in enumerate(lines) if l.strip() == START]
    end = [i for i, l in enumerate(lines) if l.strip() == END]
    if len(start) != 1 or len(end) != 1 or end[0] < start[0]:
        return None
    return "".join(lines[:start[0] + 1]), "".join(lines[start[0] + 1:end[0]]), "".join(lines[end[0]:])


def _read(path: str) -> str:
    with open(path, encoding="utf-8", newline="") as fh:
        return fh.read()


def _write(path: str, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)


def process(cls, docs_dir: str, check: bool) -> str | None:
    """Update or check one page. Returns a problem description, or None when fine/updated."""
    path = os.path.join(docs_dir, f"{cls.__name__}.md")
    rel = os.path.relpath(path, ROOT) if path.startswith(ROOT) else path
    if not os.path.exists(path):
        if check:
            return f"{rel}: page is missing"
        os.makedirs(docs_dir, exist_ok=True)
        _write(path, skeleton(cls))
        print(f"created {rel}")
        return None
    text = _read(path)
    parts = _split(text)
    if parts is None:
        return f"{rel}: no single {START} ... {END} marker pair"
    before, old, after = parts
    nl = "\r\n" if "\r\n" in text else "\n"
    new = render_block(cls).replace("\n", nl) + nl
    if old == new:
        return None
    if check:
        return f"{rel}: reference block is out of date"
    _write(path, before + new + after)
    print(f"updated {rel}")
    return None


def main(argv=None, docs_dir: str | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="report missing, marker-less or stale pages and exit 1")
    parser.add_argument("--docs-dir", default=docs_dir or DOCS_DIR,
                        help="folder of node pages (default: web/docs)")
    args = parser.parse_args(argv)
    problems = []
    for cls in load_nodes():
        problem = process(cls, args.docs_dir, args.check)
        if problem:
            problems.append(problem)
    if problems:
        stream = sys.stderr if args.check else sys.stdout
        for p in problems:
            print(("problem: " if args.check else "skipped: ") + p, file=stream)
        if args.check:
            print("Run python tools/node_docs.py to update.", file=sys.stderr)
        return 1 if args.check else 0
    if args.check:
        print("node pages are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
